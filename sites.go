type site struct {
	ID       string    `json:"id"`
	Name     string    `json:"name"`
	Domains  []string  `json:"domains"`
	Kind     string    `json:"kind"`
	Upstream string    `json:"upstream,omitempty"`
	Root     string    `json:"root,omitempty"`
	Enabled  bool      `json:"enabled"`
	Created  time.Time `json:"created"`
}

var siteID = regexp.MustCompile(`^s_[a-f0-9]{20}$`)
var domainName = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$`)

func (a *agent) readSites() ([]site, error) {
	out := []site{}
	e := loadJSON(filepath.Join(a.cfg.State, "sites.json"), &out)
	if os.IsNotExist(e) {
		e = nil
	}
	return out, e
}
func validSite(s *site) error {
	if len(s.Name) < 1 || len(s.Name) > 60 {
		return bad(400, "网站名称需为 1–60 字符")
	}
	if len(s.Domains) < 1 || len(s.Domains) > 8 {
		return bad(400, "请输入 1–8 个完整域名")
	}
	seen := map[string]bool{}
	for i, d := range s.Domains {
		d = strings.ToLower(strings.TrimSpace(d))
		if len(d) > 253 || !domainName.MatchString(d) || net.ParseIP(d) != nil || seen[d] {
			return bad(400, "域名格式错误、重复或不是完整域名")
		}
		seen[d] = true
		s.Domains[i] = d
	}
	if s.Kind != "static" && s.Kind != "proxy" {
		return bad(400, "网站类型无效")
	}
	if s.Kind == "proxy" {
		u, e := url.Parse(s.Upstream)
		if e != nil || u.Host == "" || u.User != nil || u.Scheme != "http" && u.Scheme != "https" || u.Path != "" && u.Path != "/" || u.RawQuery != "" || u.Fragment != "" || strings.ContainsAny(s.Upstream, "\n\r\t {}\"#") {
			return bad(400, "代理目标需为 http(s)://主机:端口，不含账号或路径")
		}
		if net.ParseIP(u.Hostname()) == nil && u.Hostname() != "localhost" && !domainName.MatchString(strings.ToLower(u.Hostname())) {
			return bad(400, "代理主机无效")
		}
		if p := u.Port(); p != "" {
			n, e := strconv.Atoi(p)
			if e != nil || n < 1 || n > 65535 {
				return bad(400, "代理端口需为 1–65535")
			}
		}
		s.Upstream = strings.TrimSuffix(s.Upstream, "/")
	}
	return nil
}
func renderSites(sites []site) []byte {
	var b strings.Builder
	b.WriteString("# Generated by JunPanel. Manage these sites in the local workbench.\n")
	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		b.WriteString(strings.Join(s.Domains, ", ") + " {\n  encode zstd gzip\n")
		if s.Kind == "static" {
			fmt.Fprintf(&b, "  root * %s\n  file_server\n", strconv.Quote(s.Root))
		} else {
			fmt.Fprintf(&b, "  reverse_proxy %s\n", s.Upstream)
		}
		b.WriteString("  header X-Content-Type-Options nosniff\n}\n\n")
	}
	return []byte(b.String())
}

// Existing Caddy sites remain outside the panel's editable registry.
func (a *agent) externalHosts(managed []site, hosts []string) []string {
	owned := map[string]bool{}
	for _, s := range managed {
		for _, domain := range s.Domains {
			owned[strings.ToLower(domain)] = true
		}
	}
	if data, err := os.ReadFile(filepath.Join(a.cfg.Fragments, "panel-access.caddy")); err == nil && strings.HasPrefix(string(data), "# JunPanel public HTTPS access - managed by public-access.sh\n") {
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) == 2 && fields[1] == "{" && strings.HasPrefix(fields[0], "https://") {
				if u, err := url.Parse(fields[0]); err == nil {
					owned[strings.ToLower(u.Hostname())] = true
				}
				break
			}
		}
	}
	out := []string{}
	for _, host := range hosts {
		h := strings.ToLower(host)
		ip := net.ParseIP(h)
		if owned[h] || h == "localhost" || (ip != nil && (ip.IsLoopback() || ip.IsUnspecified())) {
			continue
		}
		out = append(out, host)
	}
	return out
}
func (a *agent) applySites(sites []site) error {
	raw, e := os.ReadFile(a.cfg.Caddy)
	if e != nil {
		return bad(500, "无法读取主 Caddyfile")
	}
	expected := "import " + filepath.ToSlash(a.cfg.Fragments) + "/*.caddy"
	linked := false
	for _, line := range strings.Split(string(raw), "\n") {
		if strings.TrimSpace(line) == expected {
			linked = true
		}
	}
	if !linked {
		return bad(409, "Caddyfile 未接入面板目录，拒绝应用变更")
	}
	path := filepath.Join(a.cfg.Fragments, "managed.caddy")
	old, e := os.ReadFile(path)
	existed := e == nil
	if e != nil && !os.IsNotExist(e) {
		return e
	}
	if e = atomicBytes(path, renderSites(sites), 0644); e != nil {
		return e
	}
	restore := func() error {
		if existed {
			if e := atomicBytes(path, old, 0644); e != nil {
				return e
			}
		} else {
			os.Remove(path)
		}
		_, e := a.runner(20*time.Second, "/usr/bin/systemctl", "reload", "caddy.service")
		return e
	}
	if _, e = a.runner(20*time.Second, "/usr/sbin/runuser", "-u", "caddy", "--", "/usr/bin/caddy", "validate", "--config", a.cfg.Caddy, "--adapter", "caddyfile"); e != nil {
		if e = restore(); e != nil {
			return bad(500, "校验失败，恢复后的 Caddy 重载也失败；请立即通过 SSH 检查")
		}
		return bad(409, "Caddy 校验未通过，原片段已恢复")
	}
	if _, e = a.runner(20*time.Second, "/usr/bin/systemctl", "reload", "caddy.service"); e != nil {
		if e = restore(); e != nil {
			return bad(500, "重载失败，恢复后的重载也失败；请立即通过 SSH 检查")
		}
		return bad(409, "Caddy 重载失败，原片段已恢复")
	}
	if e = atomicJSON(filepath.Join(a.cfg.State, "sites.json"), sites, 0600); e != nil {
		if restore() != nil {
			return bad(500, "登记失败且恢复重载失败，请立即检查 Caddy")
		}
		return bad(500, "登记失败，原片段已恢复")
	}
	return nil
}
func (a *agent) siteList(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	sites, e := a.readSites()
	if e != nil {
		return e
	}
	hosts, sources, he := a.caddyInventory()
	message := ""
	if he != nil {
		message = he.Error()
	}
	state, _ := a.runner(3*time.Second, "/usr/bin/systemctl", "is-active", "caddy.service")
	send(w, 200, map[string]any{"sites": sites, "existing_hosts": hosts, "caddy_sources": sources, "external_hosts": a.externalHosts(sites, hosts), "error": message, "state": strings.TrimSpace(state), "root": a.cfg.Root})
	return nil
}
func (a *agent) siteSave(w http.ResponseWriter, r *http.Request) error {
	var req struct {
		ID       string   `json:"id"`
		Name     string   `json:"name"`
		Domains  []string `json:"domains"`
		Kind     string   `json:"kind"`
		Upstream string   `json:"upstream"`
	}
	if e := body(r, &req); e != nil {
		return e
	}
	value := site{ID: req.ID, Name: req.Name, Domains: req.Domains, Kind: req.Kind, Upstream: req.Upstream}
	if e := validSite(&value); e != nil {
		return e
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	sites, e := a.readSites()
	if e != nil {
		return e
	}
	index := -1
	own := map[string]bool{}
	for i, s := range sites {
		if s.ID == req.ID {
			index = i
			value.Root = s.Root
			value.Created = s.Created
			value.Enabled = s.Enabled
			for _, d := range s.Domains {
				own[d] = true
			}
			if s.Kind != value.Kind {
				return bad(409, "站点类型不可直接切换，请建立新站点")
			}
		} else {
			for _, d := range s.Domains {
				for _, n := range value.Domains {
					if d == n {
						return bad(409, "域名已分配给其它面板站点")
					}
				}
			}
		}
	}
	if req.ID != "" && (!siteID.MatchString(req.ID) || index < 0) {
		return bad(404, "网站不存在")
	}
	hosts, e := a.caddyHosts()
	if e != nil {
		return e
	}
	for _, d := range value.Domains {
		for _, existing := range hosts {
			if !own[d] && (existing == d || strings.HasPrefix(existing, "*.") && strings.HasSuffix(d, existing[1:])) {
				return bad(409, "域名与现有 Caddy 配置冲突")
			}
		}
	}
	fresh := ""
	if index < 0 {
		value.ID = "s_" + randomID(20)
		value.Created = time.Now()
		value.Enabled = true
		if value.Kind == "static" {
			value.Root = filepath.Join(a.cfg.Root, "sites", value.ID)
			if e = os.Mkdir(value.Root, 0755); e != nil {
				return e
			}
			fresh = value.Root
			if e = os.WriteFile(filepath.Join(value.Root, "index.html"), []byte("<!doctype html><html lang=\"zh-CN\"><meta charset=\"utf-8\"><title>网站已启航</title><body><h1>网站已启航</h1><p>在 JunPanel 的“文件”中上传你的网页。</p></body></html>"), 0644); e != nil {
				return e
			}
		}
		sites = append(sites, value)
	} else {
		sites[index] = value
	}
	if e = a.applySites(sites); e != nil {
		if fresh != "" {
			os.Remove(filepath.Join(fresh, "index.html"))
			os.Remove(fresh)
		}
		return e
	}
	send(w, 200, value)
	return nil
}
func (a *agent) siteToggle(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	rows, e := a.readSites()
	if e != nil {
		return e
	}
	for i, s := range rows {
		if s.ID == r.PathValue("id") {
			rows[i].Enabled = !s.Enabled
			if e = a.applySites(rows); e != nil {
				return e
			}
			send(w, 200, rows[i])
			return nil
		}
	}
	return bad(404, "网站不存在")
}
func (a *agent) siteDelete(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	rows, e := a.readSites()
	if e != nil {
		return e
	}
	for i, s := range rows {
		if s.ID == r.PathValue("id") {
			rows = append(rows[:i], rows[i+1:]...)
			if e = a.applySites(rows); e != nil {
				return e
			}
			send(w, 200, map[string]any{"ok": true, "message": "配置已移除，网站文件保留"})
			return nil
		}
	}
	return bad(404, "网站不存在")
}
