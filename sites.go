type site struct {
	ID       string    `json:"id"`
	Name     string    `json:"name"`
	Domains  []string  `json:"domains"`
	Kind     string    `json:"kind"`
	Upstream string    `json:"upstream,omitempty"`
	Root     string    `json:"root,omitempty"`
	Enabled  bool      `json:"enabled"`
	Created  time.Time `json:"created"`
	// A redirect site sends every request to Target.
	Target    string `json:"target,omitempty"`
	Permanent bool   `json:"permanent,omitempty"`
	KeepPath  bool   `json:"keep_path,omitempty"`
	// Access control for static and proxy sites.
	AuthUser   string   `json:"auth_user,omitempty"`
	AuthHash   string   `json:"auth_hash,omitempty"`
	AllowIPs   []string `json:"allow_ips,omitempty"`
	NoCompress bool     `json:"no_compress,omitempty"`
}

var authUser = regexp.MustCompile(`^[A-Za-z0-9._-]{1,32}$`)

// publicSite hides the password hash from the browser.
func publicSite(s site) map[string]any {
	return map[string]any{"id": s.ID, "name": s.Name, "domains": s.Domains, "kind": s.Kind, "upstream": s.Upstream, "root": s.Root, "enabled": s.Enabled, "created": s.Created,
		"target": s.Target, "permanent": s.Permanent, "keep_path": s.KeepPath, "auth_user": s.AuthUser, "auth": s.AuthHash != "", "allow_ips": s.AllowIPs, "no_compress": s.NoCompress}
}

var siteID = regexp.MustCompile(`^s_[a-f0-9]{20}$`)
var domainName = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$`)

func (a *agent) readSites() ([]site, error) {
	out := []site{}
	e := loadJSON(filepath.Join(a.cfg.State, "sites.json"), &out)
	if os.IsNotExist(e) {
		e = nil
	}
	return out, e
}
func validSite(s *site) error {
	if len(s.Name) < 1 || len(s.Name) > 60 {
		return bad(400, "网站名称需为 1–60 字符")
	}
	if len(s.Domains) < 1 || len(s.Domains) > 8 {
		return bad(400, "请输入 1–8 个完整域名")
	}
	seen := map[string]bool{}
	for i, d := range s.Domains {
		d = strings.ToLower(strings.TrimSpace(d))
		if len(d) > 253 || !domainName.MatchString(d) || net.ParseIP(d) != nil || seen[d] {
			return bad(400, "域名格式错误、重复或不是完整域名")
		}
		seen[d] = true
		s.Domains[i] = d
	}
	if s.Kind != "static" && s.Kind != "proxy" && s.Kind != "redirect" {
		return bad(400, "网站类型无效")
	}
	if s.Kind == "redirect" {
		u, e := url.Parse(s.Target)
		if e != nil || u.Scheme != "http" && u.Scheme != "https" || u.Host == "" || u.User != nil || u.Fragment != "" || strings.ContainsAny(s.Target, "\n\r\t {}\"#'`\\") || len(s.Target) > 500 {
			return bad(400, "跳转地址需为完整的 http(s):// 网址，不含空格、引号和花括号")
		}
		if net.ParseIP(u.Hostname()) == nil && !domainName.MatchString(strings.ToLower(u.Hostname())) {
			return bad(400, "跳转目标的主机名无效")
		}
		for _, d := range s.Domains {
			if strings.EqualFold(u.Hostname(), d) && (u.Path == "" || u.Path == "/") {
				return bad(400, "跳转目标不能是网站自己的域名，否则会无限跳转")
			}
		}
		s.Upstream, s.AuthUser, s.AuthHash, s.AllowIPs = "", "", "", nil
	} else {
		s.Target, s.Permanent, s.KeepPath = "", false, false
	}
	if s.AuthUser != "" && !authUser.MatchString(s.AuthUser) {
		return bad(400, "访问用户名需为 1–32 位字母、数字、点、下划线或中划线")
	}
	if len(s.AllowIPs) > 32 {
		return bad(400, "允许访问的 IP 最多 32 条")
	}
	for i, ip := range s.AllowIPs {
		ip = strings.TrimSpace(ip)
		if parsed := net.ParseIP(ip); parsed != nil {
			s.AllowIPs[i] = parsed.String()
		} else if _, block, e := net.ParseCIDR(ip); e == nil {
			s.AllowIPs[i] = block.String()
		} else {
			return bad(400, "允许访问的地址需为 IP 或 CIDR 网段，例如 203.0.113.5 或 10.0.0.0/8："+truncate(ip, 60))
		}
	}
	if s.Kind == "proxy" {
		u, e := url.Parse(s.Upstream)
		if e != nil || u.Host == "" || u.User != nil || u.Scheme != "http" && u.Scheme != "https" || u.Path != "" && u.Path != "/" || u.RawQuery != "" || u.Fragment != "" || strings.ContainsAny(s.Upstream, "\n\r\t {}\"#") {
			return bad(400, "代理目标需为 http(s)://主机:端口，不含账号或路径")
		}
		if net.ParseIP(u.Hostname()) == nil && u.Hostname() != "localhost" && !domainName.MatchString(strings.ToLower(u.Hostname())) {
			return bad(400, "代理主机无效")
		}
		if p := u.Port(); p != "" {
			n, e := strconv.Atoi(p)
			if e != nil || n < 1 || n > 65535 {
				return bad(400, "代理端口需为 1–65535")
			}
		}
		s.Upstream = strings.TrimSuffix(s.Upstream, "/")
	}
	return nil
}

// renderSites writes the managed sites. A site without access rules renders exactly
// as it always has; one with rules runs them inside route, in order: address check,
// password, then the content.
func renderSites(sites []site, authDirective string) []byte {
	var b strings.Builder
	b.WriteString("# Generated by JunPanel. Manage these sites in the local workbench.\n")
	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		if s.Kind == "redirect" {
			target, code := s.Target, "302"
			if s.KeepPath {
				target = strings.TrimSuffix(target, "/") + "{uri}"
			}
			if s.Permanent {
				code = "301"
			}
			fmt.Fprintf(&b, "%s {\n  redir %s %s\n}\n\n", strings.Join(s.Domains, ", "), target, code)
			continue
		}
		guarded := len(s.AllowIPs) > 0 || s.AuthHash != ""
		if !guarded {
			b.WriteString(strings.Join(s.Domains, ", ") + " {\n")
			if !s.NoCompress {
				b.WriteString("  encode zstd gzip\n")
			}
			if s.Kind == "static" {
				fmt.Fprintf(&b, "  root * %s\n  file_server\n", strconv.Quote(s.Root))
			} else {
				fmt.Fprintf(&b, "  reverse_proxy %s\n", s.Upstream)
			}
			b.WriteString("  header X-Content-Type-Options nosniff\n}\n\n")
			continue
		}
		b.WriteString(strings.Join(s.Domains, ", ") + " {\n  route {\n")
		if len(s.AllowIPs) > 0 {
			fmt.Fprintf(&b, "    @denied not remote_ip %s\n    respond @denied \"Forbidden\" 403\n", strings.Join(s.AllowIPs, " "))
		}
		if s.AuthHash != "" {
			fmt.Fprintf(&b, "    %s {\n      %s %s\n    }\n", authDirective, s.AuthUser, s.AuthHash)
		}
		if !s.NoCompress {
			b.WriteString("    encode zstd gzip\n")
		}
		if s.Kind == "static" {
			fmt.Fprintf(&b, "    root * %s\n    file_server\n", strconv.Quote(s.Root))
		} else {
			fmt.Fprintf(&b, "    reverse_proxy %s\n", s.Upstream)
		}
		b.WriteString("  }\n  header X-Content-Type-Options nosniff\n}\n\n")
	}
	return []byte(b.String())
}

// authDirective is basic_auth on Caddy 2.8 and later, and basicauth before.
func (a *agent) authDirective() string {
	out, e := a.runner(5*time.Second, "/usr/bin/caddy", "version")
	if e == nil {
		if m := regexp.MustCompile(`v2\.(\d+)\.`).FindStringSubmatch(out); m != nil {
			if n, _ := strconv.Atoi(m[1]); n >= 8 {
				return "basic_auth"
			}
		}
	}
	return "basicauth"
}

// Existing Caddy sites remain outside the panel's editable registry.
func (a *agent) externalHosts(managed []site, hosts []string) []string {
	owned := map[string]bool{}
	for _, s := range managed {
		for _, domain := range s.Domains {
			owned[strings.ToLower(domain)] = true
		}
	}
	if data, err := os.ReadFile(filepath.Join(a.cfg.Fragments, "panel-access.caddy")); err == nil && strings.HasPrefix(string(data), "# JunPanel public HTTPS access - managed by public-access.sh\n") {
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) == 2 && fields[1] == "{" && strings.HasPrefix(fields[0], "https://") {
				if u, err := url.Parse(fields[0]); err == nil {
					owned[strings.ToLower(u.Hostname())] = true
				}
			}
		}
	}
	out := []string{}
	for _, host := range hosts {
		h := strings.ToLower(host)
		ip := net.ParseIP(h)
		if owned[h] || h == "localhost" || (ip != nil && (ip.IsLoopback() || ip.IsUnspecified())) {
			continue
		}
		out = append(out, host)
	}
	return out
}

// caddyValidate checks the whole Caddy configuration as the caddy user. The agent's own
// service cannot always switch users ("runuser: cannot set user id: Operation not
// permitted"), so the check runs in a transient systemd unit, which is how the panel's
// public-entry changes already run; without systemd-run it is run directly.
func (a *agent) caddyValidate() (string, error) {
	check := []string{"/usr/sbin/runuser", "-u", "caddy", "--", "/usr/bin/caddy", "validate", "--config", a.cfg.Caddy, "--adapter", "caddyfile"}
	if st, e := os.Stat(a.upSystemd); e == nil && !st.IsDir() {
		args := []string{"--unit", "junpanel-validate-" + randomID(8), "--description", "JunPanel Caddy validation", "--collect", "--quiet", "--wait", "--pipe", "--"}
		return a.runner(45*time.Second, a.upSystemd, append(args, check...)...)
	}
	return a.runner(20*time.Second, check[0], check[1:]...)
}

var bcryptHash = regexp.MustCompile(`\$2[abxy]\$\d\d\$[./A-Za-z0-9]{53}`)

// caddyReason picks what Caddy said went wrong out of its validate or reload output: the
// error lines, without log noise, password hashes or very long text.
func caddyReason(out string) string {
	out = bcryptHash.ReplaceAllString(cleanText(out), "[已隐藏]")
	keep := []string{}
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "{") && strings.Contains(line, `"level":"info"`) || strings.Contains(line, "valid configuration") && !strings.Contains(line, "Error") {
			continue
		}
		keep = append(keep, line)
	}
	if len(keep) > 4 {
		keep = keep[len(keep)-4:]
	}
	return truncate(strings.Join(keep, "\n"), 600)
}

func withReason(message, out string) string {
	if reason := caddyReason(out); reason != "" {
		return message + "：\n" + reason
	}
	return message
}

func (a *agent) applySites(sites []site) error {
	raw, e := os.ReadFile(a.cfg.Caddy)
	if e != nil {
		return bad(500, "无法读取主 Caddyfile")
	}
	expected := "import " + filepath.ToSlash(a.cfg.Fragments) + "/*.caddy"
	linked := false
	for _, line := range strings.Split(string(raw), "\n") {
		if strings.TrimSpace(line) == expected {
			linked = true
		}
	}
	if !linked {
		return bad(409, "Caddyfile 未接入面板目录，拒绝应用变更")
	}
	path := filepath.Join(a.cfg.Fragments, "managed.caddy")
	old, e := os.ReadFile(path)
	existed := e == nil
	if e != nil && !os.IsNotExist(e) {
		return e
	}
	if e = atomicBytes(path, renderSites(sites, a.authDirective()), 0644); e != nil {
		return e
	}
	restore := func() error {
		if existed {
			if e := atomicBytes(path, old, 0644); e != nil {
				return e
			}
		} else {
			os.Remove(path)
		}
		_, e := a.runner(20*time.Second, "/usr/bin/systemctl", "reload", "caddy.service")
		return e
	}
	if out, e := a.caddyValidate(); e != nil {
		if e = restore(); e != nil {
			return bad(500, "校验失败，恢复后的 Caddy 重载也失败；请立即通过 SSH 检查")
		}
		return bad(409, withReason("Caddy 校验未通过，原片段已恢复", out))
	}
	if out, e := a.runner(20*time.Second, "/usr/bin/systemctl", "reload", "caddy.service"); e != nil {
		if e = restore(); e != nil {
			return bad(500, "重载失败，恢复后的重载也失败；请立即通过 SSH 检查")
		}
		return bad(409, withReason("Caddy 重载失败，原片段已恢复", out))
	}
	if e = atomicJSON(filepath.Join(a.cfg.State, "sites.json"), sites, 0600); e != nil {
		if restore() != nil {
			return bad(500, "登记失败且恢复重载失败，请立即检查 Caddy")
		}
		return bad(500, "登记失败，原片段已恢复")
	}
	return nil
}
func (a *agent) siteList(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	sites, e := a.readSites()
	if e != nil {
		return e
	}
	hosts, sources, he := a.caddyInventory()
	message := ""
	if he != nil {
		message = he.Error()
	}
	state, _ := a.runner(3*time.Second, "/usr/bin/systemctl", "is-active", "caddy.service")
	public := []map[string]any{}
	for _, s := range sites {
		public = append(public, publicSite(s))
	}
	send(w, 200, map[string]any{"sites": public, "existing_hosts": hosts, "caddy_sources": sources, "external_hosts": a.externalHosts(sites, hosts), "error": message, "state": strings.TrimSpace(state), "root": a.cfg.Root})
	return nil
}
func (a *agent) siteSave(w http.ResponseWriter, r *http.Request) error {
	var req struct {
		ID           string   `json:"id"`
		Name         string   `json:"name"`
		Domains      []string `json:"domains"`
		Kind         string   `json:"kind"`
		Upstream     string   `json:"upstream"`
		Target       string   `json:"target"`
		Permanent    bool     `json:"permanent"`
		KeepPath     bool     `json:"keep_path"`
		AuthUser     string   `json:"auth_user"`
		AuthPassword string   `json:"auth_password"`
		AllowIPs     []string `json:"allow_ips"`
		NoCompress   bool     `json:"no_compress"`
	}
	if e := body(r, &req); e != nil {
		return e
	}
	value := site{ID: req.ID, Name: req.Name, Domains: req.Domains, Kind: req.Kind, Upstream: req.Upstream, Target: req.Target, Permanent: req.Permanent, KeepPath: req.KeepPath, AuthUser: req.AuthUser, AllowIPs: req.AllowIPs, NoCompress: req.NoCompress}
	if req.AuthPassword != "" {
		if req.AuthUser == "" {
			return bad(400, "设置访问密码时需要填写用户名")
		}
		if n := len([]rune(req.AuthPassword)); n < 8 || len(req.AuthPassword) > 72 {
			return bad(400, "访问密码需为 8–72 字节")
		}
		hash, e := bcrypt.GenerateFromPassword([]byte(req.AuthPassword), 12)
		if e != nil {
			return e
		}
		value.AuthHash = string(hash)
	}
	if e := validSite(&value); e != nil {
		return e
	}
	if value.AuthUser == "" {
		value.AuthHash = ""
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	sites, e := a.readSites()
	if e != nil {
		return e
	}
	index := -1
	own := map[string]bool{}
	for i, s := range sites {
		if s.ID == req.ID {
			index = i
			value.Root = s.Root
			value.Created = s.Created
			value.Enabled = s.Enabled
			// An edit without a new password keeps the old one for the same user;
			// clearing the user turns the password off.
			if value.AuthHash == "" && value.AuthUser != "" && value.AuthUser == s.AuthUser {
				value.AuthHash = s.AuthHash
			}
			for _, d := range s.Domains {
				own[d] = true
			}
			if s.Kind != value.Kind {
				return bad(409, "站点类型不可直接切换，请建立新站点")
			}
		} else {
			for _, d := range s.Domains {
				for _, n := range value.Domains {
					if d == n {
						return bad(409, "域名已分配给其它面板站点")
					}
				}
			}
		}
	}
	if req.ID != "" && (!siteID.MatchString(req.ID) || index < 0) {
		return bad(404, "网站不存在")
	}
	hosts, e := a.caddyHosts()
	if e != nil {
		return e
	}
	for _, d := range value.Domains {
		for _, existing := range hosts {
			if !own[d] && (existing == d || strings.HasPrefix(existing, "*.") && strings.HasSuffix(d, existing[1:])) {
				return bad(409, "域名与现有 Caddy 配置冲突")
			}
		}
	}
	fresh := ""
	if index < 0 {
		value.ID = "s_" + randomID(20)
		value.Created = time.Now()
		value.Enabled = true
		if value.Kind == "static" {
			value.Root = filepath.Join(a.cfg.Root, "sites", value.ID)
			if e = os.Mkdir(value.Root, 0755); e != nil {
				return e
			}
			fresh = value.Root
			if e = os.WriteFile(filepath.Join(value.Root, "index.html"), []byte("<!doctype html><html lang=\"zh-CN\"><meta charset=\"utf-8\"><title>网站已启航</title><body><h1>网站已启航</h1><p>在 JunPanel 的“文件”中上传你的网页。</p></body></html>"), 0644); e != nil {
				return e
			}
		}
		sites = append(sites, value)
	} else {
		sites[index] = value
	}
	if value.AuthUser != "" && value.AuthHash == "" {
		return bad(400, "开启访问密码需要设置密码")
	}
	if e = a.applySites(sites); e != nil {
		if fresh != "" {
			os.Remove(filepath.Join(fresh, "index.html"))
			os.Remove(fresh)
		}
		return e
	}
	send(w, 200, publicSite(value))
	return nil
}
func (a *agent) siteToggle(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	rows, e := a.readSites()
	if e != nil {
		return e
	}
	for i, s := range rows {
		if s.ID == r.PathValue("id") {
			rows[i].Enabled = !s.Enabled
			if e = a.applySites(rows); e != nil {
				return e
			}
			send(w, 200, publicSite(rows[i]))
			return nil
		}
	}
	return bad(404, "网站不存在")
}
func (a *agent) siteDelete(w http.ResponseWriter, r *http.Request) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	rows, e := a.readSites()
	if e != nil {
		return e
	}
	for i, s := range rows {
		if s.ID == r.PathValue("id") {
			rows = append(rows[:i], rows[i+1:]...)
			if e = a.applySites(rows); e != nil {
				return e
			}
			send(w, 200, map[string]any{"ok": true, "message": "配置已移除，网站文件保留"})
			return nil
		}
	}
	return bad(404, "网站不存在")
}
