// Sites without the new options must render byte for byte as before, so an upgrade
// does not touch them.
func TestRenderSitesUnchangedWithoutOptions(t *testing.T) {
	got := string(renderSites([]site{
		{Name: "a", Domains: []string{"a.example.com", "www.a.example.com"}, Kind: "static", Root: "/srv/junpanel/sites/s_1", Enabled: true},
		{Name: "b", Domains: []string{"b.example.com"}, Kind: "proxy", Upstream: "http://127.0.0.1:8080", Enabled: true},
		{Name: "off", Domains: []string{"off.example.com"}, Kind: "proxy", Upstream: "http://127.0.0.1:1", Enabled: false},
	}, "basic_auth"))
	want := "# Generated by JunPanel. Manage these sites in the local workbench.\n" +
		"a.example.com, www.a.example.com {\n  encode zstd gzip\n  root * \"/srv/junpanel/sites/s_1\"\n  file_server\n  header X-Content-Type-Options nosniff\n}\n\n" +
		"b.example.com {\n  encode zstd gzip\n  reverse_proxy http://127.0.0.1:8080\n  header X-Content-Type-Options nosniff\n}\n\n"
	if got != want {
		t.Fatalf("output changed:\n%s\nwant:\n%s", got, want)
	}
}

