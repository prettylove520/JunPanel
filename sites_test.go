func TestSiteOptionsValidation(t *testing.T) {
	base := func(kind string) site {
		return site{Name: "x", Domains: []string{"x.example.com"}, Kind: kind, Upstream: "http://127.0.0.1:8080"}
	}
	for _, target := range []string{"", "example.com", "ftp://example.com", "javascript:alert(1)", "https://example.com/a b", "https://example.com/{uri}", "https://example.com\nrespond x", "https://u:p@example.com", "https://example.com/#x", "https://bad_host/", "https://x.example.com", "https://x.example.com/", `https://example.com/"`, "https://example.com/'x"} {
		s := base("redirect")
		s.Target = target
		if validSite(&s) == nil {
			t.Fatalf("redirect target accepted: %q", target)
		}
	}
	ok := base("redirect")
	ok.Target, ok.AuthUser, ok.AllowIPs, ok.Upstream = "https://x.example.com/new", "u", []string{"1.2.3.4"}, "http://127.0.0.1:1"
	if e := validSite(&ok); e != nil || ok.AuthUser != "" || ok.AllowIPs != nil || ok.Upstream != "" {
		t.Fatalf("redirect keeps unrelated fields: %v %+v", e, ok)
	}
	for _, ips := range [][]string{{"1.2.3.4 2.3.4.5"}, {"300.1.1.1"}, {"10.0.0.0/33"}, {"example.com"}, {"1.2.3.4\nrespond x"}, make([]string, 33)} {
		s := base("proxy")
		s.AllowIPs = ips
		if validSite(&s) == nil {
			t.Fatalf("allow list accepted: %q", ips)
		}
	}
	s := base("proxy")
	s.AllowIPs = []string{" 10.1.2.3/8 ", "2001:db8::1", "203.0.113.5"}
	if e := validSite(&s); e != nil || strings.Join(s.AllowIPs, " ") != "10.0.0.0/8 2001:db8::1 203.0.113.5" {
		t.Fatalf("allow list not normalized: %v %q", e, s.AllowIPs)
	}
	for _, paths := range [][]string{{"/a b"}, {"/a\nrespond x"}, {"/{x}"}, {"a"}, {"/\"x"}, {"/" + strings.Repeat("a", 100)}, make([]string, 21)} {
		s := base("static")
		s.BlockPaths = paths
		if validSite(&s) == nil {
			t.Fatalf("blocked paths accepted: %q", paths)
		}
	}
	bp := base("static")
	bp.BlockPaths, bp.NoCache = []string{" /.git ", "/.git", "*.sh"}, true
	if e := validSite(&bp); e != nil || strings.Join(bp.BlockPaths, " ") != "/.git *.sh" || !bp.NoCache {
		t.Fatalf("blocked paths not normalized: %v %q", e, bp.BlockPaths)
	}
	rd := base("redirect")
	rd.Target, rd.BlockPaths, rd.NoCache = "https://x.example.com/new", []string{"/.git"}, true
	if e := validSite(&rd); e != nil || rd.BlockPaths != nil || rd.NoCache {
		t.Fatalf("redirect keeps blocked paths or no-cache: %v %+v", e, rd)
	}
	for _, user := range []string{"has space", "a{b}", strings.Repeat("u", 33), "x\ny"} {
		s := base("static")
		s.AuthUser = user
		if validSite(&s) == nil {
			t.Fatalf("user accepted: %q", user)
		}
	}
}

func TestSitePasswordIsHashedKeptAndHidden(t *testing.T) {
	a := testAgent(t)
	os.WriteFile(a.cfg.Caddy, []byte("import "+filepath.ToSlash(a.cfg.Fragments)+"/*.caddy\n"), 0644)
	h := a.routes()
	r := request(h, "POST", "/sites", `{"name":"p","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080","auth_user":"team","auth_password":"short"}`, nil, nil)
	if r.Code != 400 {
		t.Fatalf("short password: %d", r.Code)
	}
	if r = request(h, "POST", "/sites", `{"name":"p","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080","auth_user":"team"}`, nil, nil); r.Code != 400 {
		t.Fatalf("user without password: %d %s", r.Code, r.Body.String())
	}
	r = request(h, "POST", "/sites", `{"name":"p","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080","auth_user":"team","auth_password":"correct horse battery","allow_ips":["203.0.113.0/24"]}`, nil, nil)
	if r.Code != 200 || strings.Contains(r.Body.String(), "$2a$") || strings.Contains(r.Body.String(), "correct horse") {
		t.Fatalf("save: %d %s", r.Code, r.Body.String())
	}
	var saved map[string]any
	json.Unmarshal(r.Body.Bytes(), &saved)
	id := saved["id"].(string)
	stored, _ := a.readSites()
	hash := stored[0].AuthHash
	if bcrypt.CompareHashAndPassword([]byte(hash), []byte("correct horse battery")) != nil {
		t.Fatal("password not stored as a bcrypt hash")
	}
	list := request(h, "GET", "/sites", "", nil, nil).Body.String()
	if strings.Contains(list, hash) || strings.Contains(list, "auth_hash") || !strings.Contains(list, `"auth":true`) {
		t.Fatalf("list exposes the hash: %s", list)
	}
	fragment, _ := os.ReadFile(filepath.Join(a.cfg.Fragments, "managed.caddy"))
	if !strings.Contains(string(fragment), "team "+hash) || !strings.Contains(string(fragment), "@denied not remote_ip 203.0.113.0/24") {
		t.Fatalf("fragment:\n%s", fragment)
	}
	// An edit without a new password keeps it; clearing the user removes it.
	request(h, "POST", "/sites", `{"id":"`+id+`","name":"renamed","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080","auth_user":"team"}`, nil, nil)
	if stored, _ = a.readSites(); stored[0].AuthHash != hash || stored[0].Name != "renamed" || len(stored[0].AllowIPs) != 0 {
		t.Fatalf("edit: %+v", stored[0])
	}
	if r = request(h, "POST", "/sites", `{"id":"`+id+`","name":"renamed","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080","auth_user":"other"}`, nil, nil); r.Code != 400 {
		t.Fatalf("new user without a password kept the old hash: %d", r.Code)
	}
	request(h, "POST", "/sites", `{"id":"`+id+`","name":"renamed","domains":["p.example.com"],"kind":"proxy","upstream":"http://127.0.0.1:8080"}`, nil, nil)
	if stored, _ = a.readSites(); stored[0].AuthHash != "" || stored[0].AuthUser != "" {
		t.Fatalf("password not removed: %+v", stored[0])
	}
}

