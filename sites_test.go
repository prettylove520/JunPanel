// caddyBins lists the Caddy binaries to test against: JUNPANEL_CADDY_BINS, or caddy.
func caddyBins(t *testing.T) []string {
	if v := os.Getenv("JUNPANEL_CADDY_BINS"); v != "" {
		return strings.Split(v, ":")
	}
	if p, e := exec.LookPath("caddy"); e == nil {
		return []string{p}
	}
	if os.Getenv("JUNPANEL_CADDY_TEST") == "1" {
		t.Fatal("JUNPANEL_CADDY_TEST=1 but caddy is not installed")
	}
	t.Skip("caddy not installed")
	return nil
}

